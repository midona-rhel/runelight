package com.midonarhel.lumina.scene;

import com.midonarhel.lumina.scene.areas.AABB;
import com.midonarhel.lumina.config.HdSettings;
import com.midonarhel.lumina.scene.areas.Area;
import com.midonarhel.lumina.scene.areas.AreaManager;
import com.midonarhel.lumina.scene.environment.Environment;
import com.midonarhel.lumina.scene.overrides.TileOverride;
import com.midonarhel.lumina.util.IntIntMap;
import java.util.ArrayList;
import javax.annotation.Nullable;
import net.runelite.api.Scene;
import net.runelite.api.WorldView;
import static net.runelite.api.Constants.CHUNK_SIZE;
import static net.runelite.api.Constants.EXTENDED_SCENE_SIZE;
import static net.runelite.api.Constants.MAX_Z;
import static net.runelite.api.Constants.SCENE_SIZE;
import static net.runelite.api.Perspective.LOCAL_COORD_BITS;

/**
 * The shading data of one loaded scene (117 HD's SceneContext, trimmed): how scene coordinates map to the world, the
 * environments that may apply, the tile override of every tile, and the shared per-vertex terrain data (smoothed
 * normals and blended unlit colours) generated by {@link com.midonarhel.lumina.scene.terrain.TerrainGenerator}.
 * Built on the map-load thread before the scene's zones are uploaded, read-only afterwards.
 */
public class SceneData
{
	public static final int TILE_OVERRIDE_MAIN = 0;
	public static final int TILE_OVERRIDE_UNDERLAY = 1;
	public static final int TILE_OVERRIDE_OVERLAY = 2;
	public static final int TILE_OVERRIDE_COUNT = 3;

	// the client's colour of hidden tile faces (117 HD's HDUtils.HIDDEN_HSL)
	public static final int HIDDEN_HSL = 12345678;

	public static final int VERTEX_IS_OVERLAY = 1 << 2;
	public static final int VERTEX_IS_UNDERLAY = 1 << 3;

	public final Scene scene;
	public final boolean topLevel;
	public final int sizeX, sizeZ;
	public final int sceneOffset;
	private final int expandedMapLoadingChunks;

	/**
	 * The south-west corner of the (unextended) scene in world coordinates, or null for non-contiguous instances.
	 */
	@Nullable
	public final int[] sceneBase;
	public final AABB sceneBounds;
	public final ArrayList<Environment> environments = new ArrayList<>();

	// 117 HD's area hiding (SceneManager.loadScene / updateAreaHiding): the hideOtherAreas areas the scene
	// intersects, and the one the player is in, outside of which nothing is drawn
	public boolean enableAreaHiding;
	public Area[] possibleAreas = new Area[0];
	@Nullable
	public volatile Area currentArea;
	// 117 HD's fillGapsInTerrain setting
	public boolean fillGaps = true;

	/**
	 * The override array the indices below refer to.
	 */
	public TileOverride[] tileOverrides = new TileOverride[0];
	public char[] tileOverrideIndices;

	public IntIntMap vertexTerrainFlags;
	public IntIntMap vertexTerrainNormalIndices;
	public short[] vertexTerrainNormals;

	// the corners of a tile's sky visibility quadrants
	public static final int SKY_SW = 0, SKY_SE = 1, SKY_NW = 2, SKY_NE = 3;
	/**
	 * The sky visibility of every tile's four corners (0-255), [level][x][z][corner] flattened, baked by
	 * {@link com.midonarhel.lumina.scene.terrain.SkyCover}; null (sub-scenes, no bake yet) is 255 everywhere.
	 */
	@Nullable
	public byte[] skyVisibility;

	public SceneData(WorldView worldView, Scene scene, int expandedMapLoadingChunks)
	{
		this.scene = scene;
		this.topLevel = worldView.isTopLevel();
		if (topLevel)
		{
			sizeX = sizeZ = EXTENDED_SCENE_SIZE;
			sceneOffset = (EXTENDED_SCENE_SIZE - SCENE_SIZE) / 2;
		}
		else
		{
			sizeX = worldView.getSizeX();
			sizeZ = worldView.getSizeY();
			sceneOffset = 0;
		}
		this.expandedMapLoadingChunks = scene.isInstance() ? 0 : expandedMapLoadingChunks;
		sceneBase = findSceneBase();
		sceneBounds = findSceneBounds(sceneBase);
		tileOverrideIndices = new char[MAX_Z * sizeX * sizeZ * TILE_OVERRIDE_COUNT];
	}

	/**
	 * 117 HD's loadScene area selection: collects the hideOtherAreas areas intersecting the scene and, if exactly
	 * one of them covers the central chunk, makes it the current area early (else the per-frame check decides).
	 */
	public void initAreaHiding()
	{
		fillGaps = HdSettings.fillGapsInTerrain;
		enableAreaHiding = sceneBase != null && HdSettings.hideUnrelatedAreas;
		if (!enableAreaHiding)
		{
			return;
		}
		int centerOffset = SCENE_SIZE / 2 & ~7;
		int centerX = sceneBase[0] + centerOffset;
		int centerY = sceneBase[1] + centerOffset;

		var possible = new ArrayList<Area>();
		for (Area area : AreaManager.AREAS_WITH_AREA_HIDING)
		{
			if (sceneBounds.intersects(area.aabbs))
			{
				possible.add(area);
			}
		}
		possibleAreas = possible.toArray(new Area[0]);

		// If area hiding can be decided based on the central chunk, apply it early
		AABB centerChunk = new AABB(centerX, centerY, centerX + 7, centerY + 7);
		for (Area possibleArea : possibleAreas)
		{
			if (!possibleArea.intersects(centerChunk))
			{
				continue;
			}

			if (currentArea != null)
			{
				// Multiple possible areas, so let's defer this
				currentArea = null;
				break;
			}
			currentArea = possibleArea;
		}
	}

	public int getTileIdx(int plane, int x, int y)
	{
		return x + y * sizeX + plane * sizeX * sizeZ;
	}

	public void setTileOverride(int plane, int x, int y, TileOverride[] overrides)
	{
		final int offset = getTileIdx(plane, x, y) * TILE_OVERRIDE_COUNT;
		for (int i = 0; i < TILE_OVERRIDE_COUNT; i++)
		{
			TileOverride override = overrides[i];
			if (override != null && override != TileOverride.NONE)
			{
				tileOverrideIndices[offset + i] = (char) (override.index + 1);
			}
		}
	}

	/**
	 * The tile override of a tile, by extended scene coordinates; one of the TILE_OVERRIDE_* types.
	 */
	public TileOverride getTileOverride(int plane, int x, int y, int type)
	{
		if (x < 0 || y < 0 || x >= sizeX || y >= sizeZ)
		{
			return TileOverride.NONE;
		}
		final int idx = tileOverrideIndices[getTileIdx(plane, x, y) * TILE_OVERRIDE_COUNT + type];
		return idx > 0 ? tileOverrides[idx - 1] : TileOverride.NONE;
	}

	public void setVertexIsOverlay(int key, boolean isOverlay)
	{
		vertexTerrainFlags.or(key, isOverlay ? VERTEX_IS_OVERLAY : VERTEX_IS_UNDERLAY);
	}

	public boolean isVertexOverlay(int key)
	{
		return vertexTerrainFlags != null && vertexTerrainFlags.test(key, VERTEX_IS_OVERLAY);
	}

	public boolean isVertexUnderlay(int key)
	{
		return vertexTerrainFlags != null && vertexTerrainFlags.test(key, VERTEX_IS_UNDERLAY);
	}

	/**
	 * The smoothed terrain normal at a vertex key, or null if the vertex has none.
	 */
	@Nullable
	public short[] getVertexNormal(int key, short[] result)
	{
		if (vertexTerrainNormalIndices == null)
		{
			return null;
		}
		int index = vertexTerrainNormalIndices.getOrDefault(key, -1);
		if (index == -1)
		{
			return null;
		}
		final int offset = index * 3;
		result[0] = vertexTerrainNormals[offset];
		result[1] = vertexTerrainNormals[offset + 1];
		result[2] = vertexTerrainNormals[offset + 2];
		return result;
	}

	/**
	 * The sky visibility (0-255) at a corner of a tile, by level and extended scene coordinates.
	 */
	public int skyVisibilityCorner(int level, int tileExX, int tileExZ, int corner)
	{
		if (skyVisibility == null || tileExX < 0 || tileExZ < 0 || tileExX >= sizeX || tileExZ >= sizeZ)
		{
			return 255;
		}
		return skyVisibility[(getTileIdx(level, tileExX, tileExZ) << 2) + corner] & 0xff;
	}

	/**
	 * The sky visibility (0-255) within a tile, bilinear between the tile's own four corners (never across a wall).
	 *
	 * @param fx the position within the tile, 0 at the west edge, 1 at the east
	 * @param fz the position within the tile, 0 at the south edge, 1 at the north
	 */
	public int skyVisibility(int level, int tileExX, int tileExZ, float fx, float fz)
	{
		if (skyVisibility == null || tileExX < 0 || tileExZ < 0 || tileExX >= sizeX || tileExZ >= sizeZ)
		{
			return 255;
		}
		fx = Math.max(0, Math.min(1, fx));
		fz = Math.max(0, Math.min(1, fz));
		int base = getTileIdx(level, tileExX, tileExZ) << 2;
		float south = (skyVisibility[base + SKY_SW] & 0xff) * (1 - fx) + (skyVisibility[base + SKY_SE] & 0xff) * fx;
		float north = (skyVisibility[base + SKY_NW] & 0xff) * (1 - fx) + (skyVisibility[base + SKY_NE] & 0xff) * fx;
		return Math.round(south * (1 - fz) + north * fz);
	}

	/**
	 * The sky visibility (0-255) at a scene-local position: its tile's quadrants, bilinear.
	 *
	 * @param minLevel the level the position belongs to at least (its tile's render level, or an entity's plane)
	 * @param slack    see {@link #skyLevel}
	 */
	public int skyVisibility(int localX, int y, int localZ, int minLevel, int slack)
	{
		if (skyVisibility == null)
		{
			return 255;
		}
		int ex = Math.max(0, Math.min(sizeX - 1, sceneOffset + (localX >> LOCAL_COORD_BITS)));
		int ez = Math.max(0, Math.min(sizeZ - 1, sceneOffset + (localZ >> LOCAL_COORD_BITS)));
		int level = skyLevel(ex, ez, y, minLevel, slack);
		return skyVisibility(level, ex, ez, (localX & 127) / 128f, (localZ & 127) / 128f);
	}

	/**
	 * The level a height belongs to at an extended tile: the highest level whose floor is at or below
	 * {@code y + slack} (y down), at least {@code minLevel}. Vertices of static models use a slack of -2, so a
	 * wall's top edge stays on its tile's level; the base of a dynamic model uses +2, so a model standing on a floor
	 * (a bridge deck, an upper storey) takes that floor's level.
	 */
	public int skyLevel(int tileExX, int tileExZ, int y, int minLevel, int slack)
	{
		minLevel = Math.max(0, Math.min(MAX_Z - 1, minLevel));
		int[][][] heights = scene.getTileHeights();
		for (int level = MAX_Z - 1; level > minLevel; level--)
		{
			if (y <= heights[level][tileExX][tileExZ] + slack)
			{
				return level;
			}
		}
		return minLevel;
	}

	public boolean intersects(Area area)
	{
		AABB[] aabbs = area.aabbs;
		if (scene.isInstance())
		{
			for (int[][] plane : scene.getInstanceTemplateChunks())
			{
				for (int[] column : plane)
				{
					for (int chunk : column)
					{
						if (chunk == -1)
						{
							continue;
						}
						int chunkX = chunk >> 14 & 1023;
						int chunkY = chunk >> 3 & 2047;
						int minX = chunkX * CHUNK_SIZE;
						int minY = chunkY * CHUNK_SIZE;
						for (var aabb : aabbs)
						{
							if (aabb.intersects(minX, minY, minX + CHUNK_SIZE - 1, minY + CHUNK_SIZE - 1))
							{
								return true;
							}
						}
					}
				}
			}
			return false;
		}

		int extended = expandedMapLoadingChunks * CHUNK_SIZE;
		int baseX = scene.getBaseX();
		int baseY = scene.getBaseY();
		var bounds = new AABB(baseX - extended, baseY - extended, baseX + SCENE_SIZE + extended - 1, baseY + SCENE_SIZE + extended - 1);
		return bounds.intersects(aabbs);
	}

	public int[] localToWorld(int localX, int localY, int plane)
	{
		int[] result = new int[3];
		sceneToWorld(localX >> LOCAL_COORD_BITS, localY >> LOCAL_COORD_BITS, plane, result);
		return result;
	}

	/**
	 * Converts (unextended) scene coordinates to world coordinates.
	 */
	public void sceneToWorld(int sceneX, int sceneY, int plane, int[] result)
	{
		if (sceneBase != null)
		{
			result[0] = sceneBase[0] + sceneX;
			result[1] = sceneBase[1] + sceneY;
			result[2] = sceneBase[2] + plane;
			return;
		}

		// Non-contiguous instance: resolve through the template chunk
		if (sceneX >= 0 && sceneY >= 0 && sceneX < SCENE_SIZE && sceneY < SCENE_SIZE)
		{
			int templateChunk = scene.getInstanceTemplateChunks()[plane][sceneX / CHUNK_SIZE][sceneY / CHUNK_SIZE];
			if (templateChunk != -1)
			{
				int rotation = 4 - (templateChunk >> 1 & 3);
				int templateChunkY = (templateChunk >> 3 & 2047) * 8;
				int templateChunkX = (templateChunk >> 14 & 1023) * 8;
				int templateChunkPlane = templateChunk >> 24 & 3;
				result[0] = templateChunkX + (sceneX & 7);
				result[1] = templateChunkY + (sceneY & 7);
				result[2] = templateChunkPlane;

				int chunkX = result[0] & -8;
				int chunkY = result[1] & -8;
				int x = result[0] & 7;
				int y = result[1] & 7;
				switch (rotation)
				{
					case 1:
						result[0] = chunkX + y;
						result[1] = chunkY + (7 - x);
						break;
					case 2:
						result[0] = chunkX + (7 - x);
						result[1] = chunkY + (7 - y);
						break;
					case 3:
						result[0] = chunkX + (7 - y);
						result[1] = chunkY + x;
						break;
				}
				return;
			}
		}
		result[0] = -1;
		result[1] = -1;
		result[2] = 0;
	}

	public void extendedSceneToWorld(int sceneExX, int sceneExY, int plane, int[] result)
	{
		sceneToWorld(sceneExX - sceneOffset, sceneExY - sceneOffset, plane, result);
	}

	/**
	 * The south-west coordinate of the scene in world coordinates, after resolving instance template chunks to their
	 * original world coordinates; null if the instance's chunks aren't contiguous.
	 */
	@Nullable
	private int[] findSceneBase()
	{
		int baseX = scene.getBaseX();
		int baseY = scene.getBaseY();
		int basePlane = 0;

		if (scene.isInstance())
		{
			boolean foundChunk = false;

			int[][][] chunks = scene.getInstanceTemplateChunks();
			for (int plane = 0; plane < chunks.length; plane++)
			{
				for (int x = 0; x < chunks[plane].length; x++)
				{
					for (int y = 0; y < chunks[plane][x].length; y++)
					{
						int chunk = chunks[plane][x][y];
						if (chunk == -1)
						{
							continue; // Ignore unfilled chunks
						}

						// Ensure the chunk isn't rotated
						int rotation = chunk >> 1 & 0x3;
						if (rotation != 0)
						{
							return null;
						}

						int chunkX = chunk >> 14 & 0x3FF;
						int chunkY = chunk >> 3 & 0x7FF;
						int chunkPlane = chunk >> 24 & 0x3;

						if (foundChunk)
						{
							if (chunkX != baseX + x || chunkY != baseY + y || chunkPlane != basePlane + plane)
							{
								return null; // Not contiguous
							}
						}
						else
						{
							// Calculate the expected unextended scene base chunk
							baseX = chunkX - x;
							baseY = chunkY - y;
							basePlane = chunkPlane - plane;
							foundChunk = true;
						}
					}
				}
			}

			if (!foundChunk)
			{
				return null;
			}

			// Transform chunk to world coordinates
			baseX <<= 3;
			baseY <<= 3;
		}

		return new int[]{baseX, baseY, basePlane};
	}

	private AABB findSceneBounds(@Nullable int[] sceneBase)
	{
		if (sceneBase != null)
		{
			int x = sceneBase[0] - sceneOffset;
			int y = sceneBase[1] - sceneOffset;
			return new AABB(x, y, x + sizeX - 1, y + sizeZ - 1);
		}

		// Assume instances are assembled from approximately adjacent chunks on the map
		int minX = Integer.MAX_VALUE;
		int minY = Integer.MAX_VALUE;
		int minZ = MAX_Z;
		int maxX = Integer.MIN_VALUE;
		int maxY = Integer.MIN_VALUE;
		int maxZ = 0;

		for (int[][] plane : scene.getInstanceTemplateChunks())
		{
			for (int[] column : plane)
			{
				for (int chunk : column)
				{
					if (chunk == -1)
					{
						continue;
					}
					int x = chunk >> 14 & 0x3FF;
					int y = chunk >> 3 & 0x7FF;
					int z = chunk >> 24 & 0x3;
					minX = Math.min(minX, x);
					minY = Math.min(minY, y);
					minZ = Math.min(minZ, z);
					maxX = Math.max(maxX, x);
					maxY = Math.max(maxY, y);
					maxZ = Math.max(maxZ, z);
				}
			}
		}

		if (maxX < minX)
		{
			return new AABB(-1, -1);
		}

		return new AABB(minX << 3, minY << 3, minZ, (maxX << 3) + CHUNK_SIZE - 1, (maxY << 3) + CHUNK_SIZE - 1, maxZ);
	}
}
