package com.midonarhel.lumina.sky;

import com.google.gson.Gson;
import com.google.gson.stream.JsonReader;
import com.midonarhel.lumina.scene.environment.Environment;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;
import lombok.extern.slf4j.Slf4j;

/**
 * What an area does to the sky and its light, from {@code sky/area_looks.json} (one entry per 117 HD environment,
 * generated by tools/import_area_looks.py; see its header). All defaults is the open overworld. Areas never move the
 * sun, and none of 117 HD's fog data is used: the fog is the sky's horizon.
 * <ul>
 * <li>{@link #ambient}, {@link #sun}: per-channel multipliers on the ambient and the sun (and moon) light</li>
 * <li>{@link #skyTint}, {@link #fogColor} with {@link #fogWeight}, {@link #haze}: a sky override, only where the
 * sky colour itself should differ. {@link SkyModel} multiplies the sky by the tint, then hazes it toward the fog
 * colour, the horizon by {@code haze} and the zenith by 0.55 of it; the fog is that horizon</li>
 * <li>{@link #underground}: no sky; the background and the fog are {@link #fogColor}, the sun is 0 and the ambient
 * is {@link SkyModel}'s cave ambient times {@link #ambient}. A float so a transition can fade it</li>
 * </ul>
 * The fields are blendable ({@link #mix}): {@link SkySource} eases between the looks of the environment manager's
 * transition. The fog colour of a look without one takes the other side's while blending so a fading-in fog never
 * passes through black.
 */
@Slf4j
public final class AreaLook
{
	public final float[] ambient = {1, 1, 1};
	public final float[] sun = {1, 1, 1};
	/** sRGB multiplier on the sky's colours. */
	public final float[] skyTint = {1, 1, 1};
	/** sRGB. Meaningful where {@link #fogWeight} is above 0. */
	public final float[] fogColor = {0, 0, 0};
	/** 1 where the look has a fog colour of its own, 0 where it has none. */
	public float fogWeight;
	public float haze;
	public float underground;

	public static final AreaLook OVERWORLD = new AreaLook();

	public void set(AreaLook o)
	{
		System.arraycopy(o.ambient, 0, ambient, 0, 3);
		System.arraycopy(o.sun, 0, sun, 0, 3);
		System.arraycopy(o.skyTint, 0, skyTint, 0, 3);
		System.arraycopy(o.fogColor, 0, fogColor, 0, 3);
		fogWeight = o.fogWeight;
		haze = o.haze;
		underground = o.underground;
	}

	/** This look = a blended toward b by t. */
	public void mix(AreaLook a, AreaLook b, float t)
	{
		mix3(ambient, a.ambient, b.ambient, t);
		mix3(sun, a.sun, b.sun, t);
		mix3(skyTint, a.skyTint, b.skyTint, t);
		float[] fa = a.fogWeight > 0 ? a.fogColor : b.fogColor;
		float[] fb = b.fogWeight > 0 ? b.fogColor : a.fogColor;
		mix3(fogColor, fa, fb, t);
		fogWeight = a.fogWeight + (b.fogWeight - a.fogWeight) * t;
		haze = a.haze + (b.haze - a.haze) * t;
		underground = a.underground + (b.underground - a.underground) * t;
	}

	public boolean sameAs(AreaLook o)
	{
		for (int i = 0; i < 3; i++)
		{
			if (ambient[i] != o.ambient[i] || sun[i] != o.sun[i] || skyTint[i] != o.skyTint[i] || fogColor[i] != o.fogColor[i])
			{
				return false;
			}
		}
		return fogWeight == o.fogWeight && haze == o.haze && underground == o.underground;
	}

	/**
	 * The fallback for an environment the data file has no entry for: the light multipliers from 117 HD's environment
	 * (its ambient and directional colour times strength divided by the OVERWORLD environment's), underground from
	 * its {@code isOverworld}, and underground its fog colour; no sky override.
	 */
	public void derive(Environment env, Environment overworld)
	{
		float[] a = env.getAmbientColor(), oa = overworld.getAmbientColor();
		float[] d = env.getDirectionalColor(), od = overworld.getDirectionalColor();
		float[] fog = env.getFogColor();
		for (int i = 0; i < 3; i++)
		{
			ambient[i] = ratio(a[i] * env.ambientStrength, oa[i] * overworld.ambientStrength);
			sun[i] = ratio(d[i] * env.directionalStrength, od[i] * overworld.directionalStrength);
			skyTint[i] = 1;
			fogColor[i] = linearToSrgb(fog[i]);
		}
		underground = env.isOverworld ? 0 : 1;
		fogWeight = underground;
		haze = 0;
	}

	private static float ratio(float v, float reference)
	{
		return reference > 1e-6f ? Math.max(0, v / reference) : 0;
	}

	private static float linearToSrgb(float c)
	{
		c = Math.max(0, c);
		return c <= 0.0031308f ? c * 12.92f : (float) (1.055 * Math.pow(c, 1 / 2.4) - 0.055);
	}

	private static void mix3(float[] out, float[] a, float[] b, float t)
	{
		for (int i = 0; i < 3; i++)
		{
			out[i] = a[i] + (b[i] - a[i]) * t;
		}
	}

	/** The looks of area_looks.json by name. */
	public static final class Table
	{
		public static final String RESOURCE = "/com/midonarhel/lumina/sky/area_looks.json";

		private final Map<String, AreaLook> looks = new HashMap<>();

		/** One entry of the file, as written by the tool; absent fields are the defaults. */
		private static final class Entry
		{
			String name;
			float[] ambient;
			float[] sun;
			float[] skyTint;
			float[] fogColor;
			Float haze;
			Boolean underground;
		}

		public static Table load(Gson gson) throws IOException
		{
			Table table = new Table();
			try (InputStream in = AreaLook.class.getResourceAsStream(RESOURCE))
			{
				if (in == null)
				{
					throw new IOException("Missing resource: " + RESOURCE);
				}
				JsonReader reader = new JsonReader(new InputStreamReader(in, StandardCharsets.UTF_8));
				reader.setLenient(true);
				Entry[] entries = gson.fromJson(reader, Entry[].class);
				if (entries == null)
				{
					throw new IOException("Empty or invalid: " + RESOURCE);
				}
				for (Entry e : entries)
				{
					if (e == null || e.name == null)
					{
						throw new IOException("Entry without a name in " + RESOURCE);
					}
					AreaLook look = new AreaLook();
					copy(look.ambient, e.ambient, e.name, "ambient");
					copy(look.sun, e.sun, e.name, "sun");
					copy(look.skyTint, e.skyTint, e.name, "skyTint");
					if (e.fogColor != null)
					{
						copy(look.fogColor, e.fogColor, e.name, "fogColor");
						look.fogWeight = 1;
					}
					look.haze = e.haze == null ? 0 : e.haze;
					look.underground = e.underground != null && e.underground ? 1 : 0;
					if (look.underground > 0 && look.fogWeight == 0)
					{
						throw new IOException("Underground look without a fogColor: " + e.name);
					}
					if (table.looks.put(e.name, look) != null)
					{
						log.warn("area_looks.json: duplicate entry {}, the later one is used", e.name);
					}
				}
			}
			return table;
		}

		private static void copy(float[] out, float[] v, String name, String field) throws IOException
		{
			if (v == null)
			{
				return;
			}
			if (v.length != 3)
			{
				throw new IOException(name + "." + field + ": 3 numbers expected");
			}
			System.arraycopy(v, 0, out, 0, 3);
		}

		/** The look of the 117 HD environment with this key (or area name without one), or null. */
		public AreaLook get(String name)
		{
			return looks.get(name);
		}

		public int size()
		{
			return looks.size();
		}
	}
}
