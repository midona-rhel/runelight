/**
 * The plugin.client's interface over the scene: its texture, the banded upload (InterfaceUpload) started and finished each
 * frame, and the textured quad that draws it with the UI scaler. Split out of the plugin class verbatim; it reads the
 * plugin's state through {@code plugin}.
 */
public final class UiBlit
{
	private final LuminaPlugin plugin;

	public UiBlit(LuminaPlugin plugin)
	{
		this.plugin = plugin;
	}

	public void init()
	{
		plugin.interfacePbo = glGenBuffers();

		plugin.interfaceTexture = glGenTextures();
		glBindTexture(GL_TEXTURE_2D, plugin.interfaceTexture);
		glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
		glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
		glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
		glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
		plugin.interfaceFilter = GL_LINEAR;
		glBindTexture(GL_TEXTURE_2D, 0);
	}

	public void prepare(int canvasWidth, int canvasHeight)
	{
		if (canvasWidth != plugin.lastCanvasWidth || canvasHeight != plugin.lastCanvasHeight)
		{
			plugin.lastCanvasWidth = canvasWidth;
			plugin.lastCanvasHeight = canvasHeight;

			glBindTexture(GL_TEXTURE_2D, plugin.interfaceTexture);
			glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, canvasWidth, canvasHeight, 0, GL_BGRA, GL_UNSIGNED_BYTE, 0);
			glBindTexture(GL_TEXTURE_2D, 0);
		}

		final BufferProvider bufferProvider = plugin.client.getBufferProvider();
		// copied on worker threads while the composite is submitted; interfaceUpload.finish fills the texture
		plugin.interfaceUpload.start(plugin.interfacePbo, bufferProvider.getPixels(), bufferProvider.getWidth(),
			bufferProvider.getHeight());
	}

	public void finish()
	{
		if (plugin.interfaceFinished)
		{
			return;
		}
		plugin.interfaceFinished = true;
		plugin.cpuTimer.begin(CpuTimer.UI_UPLOAD);
		plugin.interfaceUpload.await();
		plugin.cpuTimer.end(CpuTimer.UI_UPLOAD);
		// the composite samples none of unit 0, and the interface draws from it
		glActiveTexture(GL_TEXTURE0);
		plugin.interfaceUpload.finish(plugin.interfaceTexture);
	}

	public void draw(final int overlayColor, final int canvasHeight, final int canvasWidth)
	{
		glEnable(GL_BLEND);
		glBlendFunc(GL_ONE, GL_ONE_MINUS_SRC_ALPHA);
		glBindTexture(GL_TEXTURE_2D, plugin.interfaceTexture);

		// Use the texture bound in the first pass
		final UIScalingMode uiScalingMode = plugin.config.uiScalingMode();
		glUseProgram(plugin.glUiProgram);
		glUniform2i(plugin.uniTexSourceDimensions, canvasWidth, canvasHeight);
		glUniform4f(plugin.uniUiAlphaOverlay,
			(overlayColor >> 16 & 0xFF) / 255f,
			(overlayColor >> 8 & 0xFF) / 255f,
			(overlayColor & 0xFF) / 255f,
			(overlayColor >>> 24) / 255f
		);
		glUniform1f(plugin.uniUiColorblindIntensity, plugin.config.colorBlindIntensity());

		final AffineTransform t = plugin.dpiTransform();

		if (plugin.client.isStretchedEnabled())
		{
			Dimension dim = plugin.client.getStretchedDimensions();
			plugin.glDpiAwareViewport(0, 0, dim.width, dim.height);
			glUniform2i(plugin.uniTexTargetDimensions, plugin.getScaledValue(t.getScaleX(), dim.width), plugin.getScaledValue(t.getScaleY(), dim.height));
		}
		else
		{
			plugin.glDpiAwareViewport(0, 0, canvasWidth, canvasHeight);
			glUniform2i(plugin.uniTexTargetDimensions, plugin.getScaledValue(t.getScaleX(), canvasWidth), plugin.getScaledValue(t.getScaleY(), canvasHeight));
		}

		// Set the sampling function used when stretching the UI.
		// This is probably better done with sampler objects instead of texture parameters, but this is easier and likely more portable.
		// See https://www.khronos.org/opengl/wiki/Sampler_Object for details.
		// GL_NEAREST makes sampling for bicubic/xBR simpler, so it should be used whenever linear/hybrid isn't
		final int function = uiScalingMode == UIScalingMode.LINEAR || uiScalingMode == UIScalingMode.HYBRID ? GL_LINEAR : GL_NEAREST;
		if (function != plugin.interfaceFilter)
		{
			glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, function);
			glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, function);
			plugin.interfaceFilter = function;
		}

		// Texture on UI
		glBindVertexArray(plugin.vaoUiHandle);
		glDrawArrays(GL_TRIANGLE_FAN, 0, 4);

		// Reset
		glBindTexture(GL_TEXTURE_2D, 0);
		glBindVertexArray(0);
		glUseProgram(0);
		glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
		glDisable(GL_BLEND);
	}
}
